const FA = '۰۱۲۳۴۵۶۷۸۹';
/** Persian digits; thousands separator ٬ */
export function fa(n: number | string, group = false) {
  let s = String(n);
  if (group) s = s.replace(/\B(?=(\d{3})+(?!\d))/g, '٬');
  return s.replace(/\d/g, (d) => FA[+d]);
}

